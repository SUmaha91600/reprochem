"""Runs the LangGraph agent on the 5 requests of the S1 agent sheet.

    uv run --extra agents python agentic/S5_langgraph/run_requests.py          # all
    uv run --extra agents python agentic/S5_langgraph/run_requests.py 2 5      # some

The requests are the ones of agentic/S1_workflow_or_agent, adapted to papers of
the gold set (data/papers/md) and to 3 papers instead of 20 for request 3.
Writes runs.md next to this file.
"""
from __future__ import annotations

import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import tools as T  # noqa: E402
from graph import build  # noqa: E402

REQUESTS = {
    1: "Read the Computational Details of paper 2202.02370 and give me the 7 fields "
       "(functional, basis set, dispersion, solvation, charge, multiplicity, software) as JSON.",
    2: "Turn this protocol into a ready-to-run job for my molecule, water (SMILES O, 1 heavy atom): "
       "the geometry is optimised at wB97X-D/def2-TZVP with SMD solvation in water, "
       "charge 0, singlet, with Gaussian 16.",
    3: "For papers 2202.02370, 2406.02341 and 2207.04987, tell me which ones report all 7 fields "
       "and which ones omit charge, multiplicity or solvation.",
    4: "Paper 2207.04987 generated conformers with CREST (GFN2-xTB) and re-optimised the lowest ones "
       "at the paper's DFT level. Reproduce the ensemble for my molecule, butane (SMILES CCCC, "
       "4 heavy atoms, neutral singlet), and tell me which conformer is the global minimum at their level.",
    5: "My relative energies differ from the results of paper 2207.04987 by up to 2 kcal/mol. "
       "Find out which settings of the paper I should check.",
}
DECISION = {1: "workflow", 2: "workflow", 3: "workflow", 4: "agent", 5: "agent"}


def run(n: int, graph) -> str:
    T.reset(REQUESTS[n])
    start = time.time()
    out = graph.invoke({"messages": [("user", REQUESTS[n])]}, {"recursion_limit": 30})
    calls = [f"{c['name']}({', '.join(f'{k}={str(v)[:40]}' for k, v in c['args'].items())})"
             for m in out["messages"] for c in (getattr(m, "tool_calls", None) or [])]
    reflections = sum(1 for m in out["messages"] if m.type == "human" and m.content.startswith("Reflection"))
    answer = out["messages"][-1].content.strip()
    return (f"## Request {n} ({DECISION[n]} in the S1 sheet)\n\n> {REQUESTS[n]}\n\n"
            f"**Tool calls ({len(calls)}):**\n\n" + "\n".join(f"{i}. `{c}`" for i, c in enumerate(calls, 1))
            + f"\n\n**Reflection steps:** {reflections} · **Time:** {time.time() - start:.0f} s\n\n"
            f"**Answer:**\n\n{answer[:2500]}\n")


def main() -> int:
    picked = [int(a) for a in sys.argv[1:]] or sorted(REQUESTS)
    graph = build()
    parts = ["# ReproChem · LangGraph agent on the 5 requests of the S1 sheet\n",
             "Generated by `run_requests.py`. Agent model: config.yaml `agent`; "
             "extraction model: the `model` section or `REPROCHEM_MODEL`.\n"]
    for n in picked:
        print(f"request {n}...", file=sys.stderr)
        try:
            parts.append(run(n, graph))
        except Exception as err:                                   # noqa: BLE001
            parts.append(f"## Request {n}\n\nFAILED: {type(err).__name__}: {str(err)[:300]}\n")
    out = HERE / "runs.md"
    if out.exists() and len(picked) < len(REQUESTS):      # keep the other requests of the last run
        old = re.split(r"(?m)^(?=## Request )", out.read_text(encoding="utf-8"))
        kept = {int(re.match(r"## Request (\d+)", b).group(1)): b for b in old if b.startswith("## Request")}
        kept.update(dict(zip(picked, parts[2:])))
        parts = parts[:2] + [kept[n].rstrip() + "\n" for n in sorted(kept)]
    out.write_text("\n".join(parts), encoding="utf-8")
    print("\n".join(parts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
