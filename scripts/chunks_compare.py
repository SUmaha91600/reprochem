"""200 versus 400 words per section: accuracy, time and cost, measured.

    uv run python scripts/chunks_compare.py     # after scripts/mac_chunks.sh

Reads eval/report_student-lora-200w.json and eval/report_student-lora-400w.json
(same LoRA student, same 13 gold papers, same session) and writes
docs/chunks_400.{md,json}.

Time: seconds per paper, paired on the same papers (each paper is its own
control, so a slow paper does not bias the comparison).
Cost: what the 840 teacher answers would cost through the API, scaled by the
measured token ratio from docs/retrieval_ablation.json (the $5 at 200 words
comes from docs/evaluation_report.md §8).
"""
from __future__ import annotations

import json
import random
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ["functional", "basis", "dispersion", "solvation", "charge", "multiplicity", "software"]
B, SEED = 2000, 0
API_COST_200W = 5.0   # docs/evaluation_report.md §8, list price of 22 Sep 2026


def load(words: int) -> dict:
    p = ROOT / f"eval/report_student-lora-{words}w.json"
    if not p.exists():
        sys.exit(f"missing {p.relative_to(ROOT)}: run bash scripts/mac_chunks.sh first")
    return json.loads(p.read_text())


def boot_mean(xs: list[float]) -> tuple[float, float, float]:
    rng = random.Random(SEED)
    means = sorted(statistics.fmean(rng.choices(xs, k=len(xs))) for _ in range(B))
    return statistics.fmean(xs), means[int(0.025 * B)], means[int(0.975 * B) - 1]


def by_paper(rep: dict) -> dict:
    return {p["paper_id"]: p for p in rep["per_paper"]}


def main() -> int:
    a, b = by_paper(load(200)), by_paper(load(400))
    papers = [pid for pid in a if pid in b]
    sec_a = [a[p]["seconds"] for p in papers]
    sec_b = [b[p]["seconds"] for p in papers]
    ratio = [y / x for x, y in zip(sec_a, sec_b) if x > 0]
    correct_d = [float(b[p]["fields"][f]["correct"]) - float(a[p]["fields"][f]["correct"])
                 for p in papers for f in FIELDS]

    abl = json.loads((ROOT / "docs/retrieval_ablation.json").read_text())
    tok = {r["size"]: r["median_prompt_tokens"] for r in abl["rows"]
           if r["retriever"] == "bm25" and r["chunking"] == "sections" and r.get("size") in (200, 400)}
    tok_ratio = tok[400] / tok[200]

    ra, rb = load(200), load(400)
    out = {
        "papers": len(papers),
        "median_seconds": {"200": statistics.median(sec_a), "400": statistics.median(sec_b)},
        "total_seconds": {"200": round(sum(sec_a), 1), "400": round(sum(sec_b), 1)},
        "time_ratio_per_paper": [round(x, 3) for x in boot_mean(ratio)],
        "correct_field": {"200": ra["field_accuracy"], "400": rb["field_accuracy"]},
        "correct_field_paired_diff": [round(x, 3) for x in boot_mean(correct_d)],
        "invented_value": {"200": ra["hallucination"], "400": rb["hallucination"]},
        "median_prompt_tokens": tok,
        "token_ratio": round(tok_ratio, 3),
        "api_cost_teacher_usd": {"200": API_COST_200W, "400": round(API_COST_200W * tok_ratio, 1)},
        "failed": {"200": ra["n_failed"], "400": rb["n_failed"]},
    }
    (ROOT / "docs/chunks_400.json").write_text(json.dumps(out, indent=2))

    f = lambda v: "—" if v is None else f"{v[0]:.2f} [{v[1]:.2f}–{v[2]:.2f}]"
    r = out["time_ratio_per_paper"]
    d = out["correct_field_paired_diff"]
    L = ["# 200 versus 400 words per section", "",
         f"*Generated by `scripts/chunks_compare.py`. LoRA student, {len(papers)} gold papers, "
         "both runs in the same session on the same Mac.*", "",
         "| | 200 words | 400 words |", "|---|---|---|",
         f"| correct field | {f(ra['field_accuracy'])} | {f(rb['field_accuracy'])} |",
         f"| invented value if absent | {f(ra['hallucination'])} | {f(rb['hallucination'])} |",
         f"| median seconds per paper | {out['median_seconds']['200']:.1f} | {out['median_seconds']['400']:.1f} |",
         f"| total seconds, {len(papers)} papers | {out['total_seconds']['200']} | {out['total_seconds']['400']} |",
         f"| median prompt tokens (measured) | {tok[200]} | {tok[400]} |",
         f"| teacher through the API (USD) | {API_COST_200W:.0f} | ≈ {out['api_cost_teacher_usd']['400']} |",
         f"| failed papers | {ra['n_failed']} | {rb['n_failed']} |", "",
         f"Time per paper, 400 / 200, paired: **×{r[0]:.2f} [{r[1]:.2f}–{r[2]:.2f}]**.",
         f"Correct field, 400 − 200, paired on {len(correct_d)} fields: "
         f"**{d[0]:+.3f} [{d[1]:+.3f}, {d[2]:+.3f}]**"
         + (" (interval includes 0: no proven difference)." if d[1] <= 0 <= d[2] else "."), "",
         "API cost at 400 words = the 200-word cost × the measured token ratio "
         f"({tok_ratio:.2f}); the student itself costs nothing per document, it costs time."]
    (ROOT / "docs/chunks_400.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
