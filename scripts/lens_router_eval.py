"""ReproChem Lens without the microphone: does the right diagram open when the
sentence is heard perfectly?

    uv run python scripts/lens_router_eval.py     # ~1 s, needs node -> docs/lens_router.{md,json}

It runs the exact router of the demo (app/lens/router.js) on
  - the 20 reference sentences of the voice benchmark (app/lens/voicetest.html),
  - 6 false-premise questions ("the BP86 basis set") and their 6 correct twins.
This isolates the router: with speech, voicetest.html adds the recognition
errors (WER) on top. Router accuracy here is the ceiling of intent accuracy
with a microphone.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LENS = ROOT / "app/lens"

PREMISES = [  # (sentence, expected concept, premise expected?)
    ("Explain the BP86 basis set", "bp86", True),
    ("What is the B3LYP basis?", "b3lyp", True),
    ("Which functional is 6-311++G(d,p)?", "b6311", True),
    ("Explain the def2 functional", "b6311", True),
    ("Tell me about the BP86 base", "bp86", True),
    ("Is cc-pVTZ a good functional?", "b6311", True),
    ("Explain the BP86 functional", "bp86", False),
    ("What is the B3LYP functional?", "b3lyp", False),
    ("Which basis set is 6-311++G(d,p)?", "b6311", False),
    ("Explain the def2 basis set", "b6311", False),
    ("Tell me about BP86", "bp86", False),
    ("Is cc-pVTZ a good basis set?", "b6311", False),
]


def sentences() -> list[tuple[str, str]]:
    html = (LENS / "voicetest.html").read_text(encoding="utf-8")
    block = html[html.index("const SENTENCES = ["):]
    block = block[:block.index("];")]
    return re.findall(r'\["(.+?)",\s*"([a-z0-9]+)"\]', block)


def route(texts: list[str]) -> list[dict]:
    js = ("global.window={};require(%r);require(%r);"
          "console.log(JSON.stringify(%s.map(s=>window.LensRouter.route(s))))") % (
        str(LENS / "concepts.js"), str(LENS / "router.js"), json.dumps(texts))
    return json.loads(subprocess.run(["node", "-e", js], capture_output=True, text=True,
                                     timeout=30, check=True).stdout)


def main() -> int:
    ref = sentences()
    got = route([s for s, _ in ref])
    rows = [{"sentence": s, "expected": e, "routed": g["id"], "video": g.get("video", False),
             "ok": g["id"] == e} for (s, e), g in zip(ref, got)]
    prem = route([s for s, _, _ in PREMISES])
    prows = [{"sentence": s, "expected": e, "routed": g["id"], "premise_expected": p,
              "premise_shown": bool(g.get("premise")), "ok": g["id"] == e and bool(g.get("premise")) == p}
             for (s, e, p), g in zip(PREMISES, prem)]
    n_ok, n_p = sum(r["ok"] for r in rows), sum(r["ok"] for r in prows)
    caught = sum(r["premise_shown"] for r in prows if r["premise_expected"])
    false_alarm = sum(r["premise_shown"] for r in prows if not r["premise_expected"])
    out = {"router_accuracy": [n_ok, len(rows)], "premise_cases": [n_p, len(prows)],
           "premises_caught": [caught, 6], "false_alarms": [false_alarm, 6],
           "sentences": rows, "premises": prows}
    (ROOT / "docs/lens_router.json").write_text(json.dumps(out, indent=2, ensure_ascii=False))
    L = ["# Lens router, text input (no microphone)", "",
         "*Generated by `scripts/lens_router_eval.py`: the demo's router (`app/lens/router.js`) on the "
         "exact text. With speech, `voicetest.html` adds recognition errors on top.*", "",
         f"- Right concept on the 20 benchmark sentences: **{n_ok}/{len(rows)}**",
         f"- False premises caught: **{caught}/6**; false alarms on the correct twins: **{false_alarm}/6**", "",
         "| Sentence | Expected | Opened | OK |", "|---|---|---|---|"]
    L += [f"| {r['sentence']} | {r['expected']} | {r['routed'] or '—'} | {'yes' if r['ok'] else '**no**'} |"
          for r in rows + prows]
    (ROOT / "docs/lens_router.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:7]))
    for r in rows + prows:
        if not r["ok"]:
            print("  miss:", r["sentence"], "->", r["routed"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
