"""Evaluation reports -> docs/results.md. No figure is copied by hand.

    uv run python scripts/results_md.py                  # the three benchmark rows
    uv run python scripts/results_md.py eval/report_*.json

What the file contains:
  1. the main table, each rate with its 95% bootstrap interval;
  2. accuracy per field, with the number of cases behind each figure;
  3. BM25 retrieval recall (is the gold value in the 3 passages the model
     sees?), recomputed here without any model call;
  4. every error of the last system, labelled retrieval or generation;
  5. the training set and the loss curve read from logs/train.log.
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

from eval import FIELDS, normalise  # noqa: E402

DEFAULT = ["eval/report_teacher.json", "eval/report_student-base.json",
           "eval/report_student-lora.json"]
METRICS = [
    ("field_accuracy", "Correct field (gold set)"),
    ("hallucination", "Invented value when the field is absent ↓"),
    ("abstention", "NOT_FOUND when the field is absent"),
    ("quote_in_paper", "Quote found in the paper"),
    ("citation_verified", "Value found in its quote"),
    ("teacher_agreement", "Agreement with the teacher"),
    ("runnable", "Compiled protocol that converges (water)"),
]


def fmt(v) -> str:
    return "—" if v is None else f"{v[0]:.2f} [{v[1]:.2f} – {v[2]:.2f}]"


def retrieval_recall(testset: list[dict]) -> dict:
    """For each field present in the paper: does the gold value appear in the
    BM25 passages the model receives? Deterministic, no model needed."""
    from app.pipeline import CFG, Retriever, parse, retrieve

    out = {}
    for t in testset:
        md = (ROOT / t["markdown_path"]).read_text(encoding="utf-8", errors="replace")
        r = Retriever(parse(md, t["paper_id"]), CFG["retrieval"])
        for f in FIELDS:
            want = t["fields"][f]
            if want == "NOT_FOUND":
                continue
            text = normalise(" ".join(c.text for c, _ in retrieve(r, f, mode="bm25")))
            out[(t["paper_id"], f)] = normalise(want) in text
    return out


def train_log() -> dict:
    p = ROOT / "logs/train.log"
    if not p.exists():
        return {}
    s = p.read_text(errors="replace")
    base = re.findall(r"base (\S+) · batch (\d+)", s)
    starts = [m.start() for m in re.finditer(r"Iter 1: Val loss", s)]
    if starts:                      # several runs in one log: keep the last one
        s = s[starts[-1]:]
    val = [(int(i), float(v)) for i, v in re.findall(r"Iter (\d+): Val loss ([\d.]+)", s)]
    tr = [(int(i), float(v)) for i, v in re.findall(r"Iter (\d+): Train loss ([\d.]+)", s)]
    mem = [float(m) for m in re.findall(r"Peak mem ([\d.]+) GB", s)]
    return {"val": val, "train": tr, "peak_mem": max(mem) if mem else None,
            "base": base[-1] if base else None}


def main() -> int:
    paths = sys.argv[1:] or DEFAULT
    reps = []
    for p in paths:
        fp = ROOT / p
        if fp.exists():
            reps.append(json.loads(fp.read_text()))
        else:
            print(f"missing: {p}", file=sys.stderr)
    if not reps:
        print("no report: run bash scripts/mac_bench.sh first", file=sys.stderr)
        return 1
    names = [r["label"] for r in reps]
    testset = [json.loads(l) for l in (ROOT / "eval/testset.jsonl").open() if l.strip()]
    n_fields = sum(1 for t in testset for f in FIELDS)
    n_absent = sum(1 for t in testset for f in FIELDS if t["fields"][f] == "NOT_FOUND")

    L = ["# Benchmark results",
         "",
         "*Generated by `scripts/results_md.py` from `eval/report_*.json`. "
         "Do not edit by hand: rerun the script.*",
         "",
         f"Gold set: **{len(testset)} papers**, {n_fields} fields, of which **{n_absent}** "
         f"are absent from the paper (NOT_FOUND). BM25 retrieval, 3 passages per field, "
         "sections of at most 200 words. In brackets: 95% bootstrap interval.",
         "",
         "## 1 · Main table",
         "",
         "| Metric | " + " | ".join(names) + " |",
         "|---|" + "---|" * len(names)]
    for k, lbl in METRICS:
        L.append(f"| {lbl} | " + " | ".join(fmt(r.get(k)) for r in reps) + " |")
    L.append("| Seconds per paper (median) | "
             + " | ".join("—" if r.get("label") == "teacher" else str(r.get("median_seconds"))
                          for r in reps) + " |")
    L.append("| Model | " + " | ".join(str(r.get("model")) for r in reps) + " |")
    L.append("| Papers scored / failed | "
             + " | ".join(f"{r['n_papers']} / {r.get('n_failed', 0)}" for r in reps) + " |")
    L += ["", "The teacher row scores Claude's labels on the same passages as the "
          "student, so no timing or compilation is attributed to it.", ""]

    # 2 · per field
    L += ["## 2 · Accuracy per field", "",
          "| Field | present / absent | " + " | ".join(names) + " |",
          "|---|---|" + "---|" * len(names)]
    for f in FIELDS:
        pres = sum(1 for t in testset if t["fields"][f] != "NOT_FOUND")
        cells = []
        for r in reps:
            vals = [p["fields"][f]["correct"] for p in r["per_paper"]]
            cells.append(f"{sum(vals)}/{len(vals)}" if vals else "—")
        L.append(f"| {f} | {pres} / {len(testset) - pres} | " + " | ".join(cells) + " |")
    L.append("")

    # 3 · retrieval
    rec = retrieval_recall(testset)
    by_f = collections.defaultdict(list)
    for (pid, f), ok in rec.items():
        by_f[f].append(ok)
    tot = list(rec.values())
    L += ["## 3 · Retrieval on its own", "",
          "Share of fields present in the paper whose gold value appears in the "
          "3 BM25 passages sent to the model. This caps any model placed after "
          "it: a value missing from the passages cannot be quoted.", "",
          "| Field | recall@3 |", "|---|---|"]
    for f in FIELDS:
        v = by_f.get(f, [])
        L.append(f"| {f} | {sum(v)}/{len(v)} |" if v else f"| {f} | — |")
    if tot:
        L.append(f"| **all** | **{sum(tot)}/{len(tot)} = {sum(tot) / len(tot):.2f}** |")
    L.append("")

    # 4 · errors of the last system
    last = reps[-1]
    errs = collections.Counter()
    lines = []
    for p in last["per_paper"]:
        for f in FIELDS:
            row = p["fields"][f]
            if row["correct"]:
                continue
            if row["gold"] == "NOT_FOUND":
                kind = "generation: invented value"
            elif row["value"] == "NOT_FOUND":
                kind = ("retrieval: value not in passages" if not rec.get((p["paper_id"], f))
                        else "generation: wrong abstention")
            else:
                kind = ("retrieval: value not in passages" if not rec.get((p["paper_id"], f))
                        else "generation: wrong value")
            errs[kind] += 1
            lines.append(f"| {p['paper_id']} | {f} | {row['gold']} | {row['value']} | {kind} |")
    L += [f"## 4 · Errors of `{last['label']}`", "",
          "| Type | count |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in errs.most_common()]
    L += ["", "| Paper | Field | Gold set | Predicted | Diagnosis |", "|---|---|---|---|---|"]
    L += lines or ["| — | — | — | — | no errors |"]
    L.append("")

    # 5 · training
    sft = {s: sum(1 for _ in (ROOT / f"data/sft/{s}.jsonl").open())
           for s in ("train", "valid") if (ROOT / f"data/sft/{s}.jsonl").exists()}
    tl = train_log()
    L += ["## 5 · Student training", "",
          f"SFT examples: {sft.get('train', '—')} for training, {sft.get('valid', '—')} "
          "for validation (disjoint papers, gold-set papers excluded)."]
    if tl.get("base"):
        L.append(f"Base: `{tl['base'][0]}`, batch {tl['base'][1]}.")
    if tl.get("val"):
        L += ["", "| Iteration | validation loss |", "|---|---|"]
        L += [f"| {i} | {v:.3f} |" for i, v in tl["val"]]
    if tl.get("peak_mem"):
        L.append(f"\nPeak memory during training: {tl['peak_mem']:.1f} GB.")
    L.append("")

    out = ROOT / "docs/results.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"\nwritten: {out.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
